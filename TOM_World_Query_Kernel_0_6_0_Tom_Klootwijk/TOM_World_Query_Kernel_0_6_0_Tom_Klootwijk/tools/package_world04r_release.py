def make_deterministic_zip() -> list[str]:
    ZIP_PATH.unlink(missing_ok=True)
    ZIP_ALIAS.unlink(missing_ok=True)
    names: list[str] = []
    with zipfile.ZipFile(ZIP_PATH, "w") as archive:
        for path in package_files():
            rel = path.relative_to(ROOT).as_posix()
            name = f"{PACKAGE_NAME}/{rel}"
            info = zipfile.ZipInfo(name, date_time=FIXED_TIME)
            info.create_system = 3
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o100644 & 0xFFFF) << 16
            info.flag_bits |= 0x800
            archive.writestr(
                info,
                path.read_bytes(),
                compress_type=zipfile.ZIP_DEFLATED,
                compresslevel=9,
            )
            names.append(name)
    return names


def validate_zip_name(name: str) -> None:
    value = PurePosixPath(name)
    if value.is_absolute() or not value.parts or value.parts[0] != PACKAGE_NAME:
        raise RuntimeError(f"unsafe archive path {name!r}")
    if any(part in {"", ".", ".."} for part in value.parts):
        raise RuntimeError(f"unsafe archive path {name!r}")


def verify_zip(expected_names: list[str]) -> None:
    with zipfile.ZipFile(ZIP_PATH, "r") as archive:
        infos = archive.infolist()
        names = [info.filename for info in infos]
        if names != expected_names or names != sorted(names) or len(names) != len(set(names)):
            raise RuntimeError("archive member ordering/identity mismatch")
        for info in infos:
            validate_zip_name(info.filename)
            if info.date_time != FIXED_TIME:
                raise RuntimeError(f"archive timestamp is not fixed: {info.filename}")
            if ((info.external_attr >> 16) & 0xFFFF) != 0o100644:
                raise RuntimeError(f"archive mode is not fixed: {info.filename}")
        bad = archive.testzip()
        if bad is not None:
            raise RuntimeError(f"archive CRC failure at {bad}")


def verify_internal_inventory(root: Path) -> None:
    manifest = json.loads((root / "checksums/PACKAGE_MANIFEST.json").read_text(encoding="utf-8"))
    for item in manifest.get("files", []):
        path = root / item["path"]
        if not path.is_file() or path.stat().st_size != item["bytes"] or sha256(path) != item["sha256"]:
            raise RuntimeError(f"internal package manifest mismatch: {item['path']}")

    checksum_path = root / "checksums/SHA256SUMS.txt"
    seen: set[str] = set()
    for line in checksum_path.read_text(encoding="utf-8").splitlines():
        digest, rel = line.split("  ", 1)
        path = root / rel
        if not path.is_file() or sha256(path) != digest:
            raise RuntimeError(f"internal checksum mismatch: {rel}")
        seen.add(rel)
    expected = {
        path.relative_to(root).as_posix()
        for path in root.rglob("*")
        if path.is_file()
        and path != checksum_path
        and not any(part in EXCLUDED_PARTS for part in path.relative_to(root).parts)
    }
    if seen != expected:
        raise RuntimeError(
            f"internal checksum inventory mismatch; missing={sorted(expected-seen)}, extra={sorted(seen-expected)}"
        )


def run_command(cmd: list[str], cwd: Path, timeout: int = 600) -> subprocess.CompletedProcess[str]:
    env = os.environ.copy()
    env["PYTHONPATH"] = str(cwd / "src/python")
    result = subprocess.run(cmd, cwd=cwd, env=env, text=True, capture_output=True, timeout=timeout)
    if result.returncode:
        raise RuntimeError(
            f"archive replay command failed ({result.returncode}): {' '.join(cmd)}\n"
            f"STDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}"
        )
    return result


