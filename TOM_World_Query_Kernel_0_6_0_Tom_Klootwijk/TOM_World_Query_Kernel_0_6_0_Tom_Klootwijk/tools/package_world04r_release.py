def clean_archive_replay() -> dict[str, Any]:
    expected_files = {rel: sha256(ROOT / rel) for rel in REPLAY_FILES}
    expected_store = tree_manifest(ROOT / "examples/world04r/continuation_store")
    with tempfile.TemporaryDirectory(prefix="tom-world04r-final-archive-") as td:
        base = Path(td)
        with zipfile.ZipFile(ZIP_PATH, "r") as archive:
            for info in archive.infolist():
                validate_zip_name(info.filename)
            archive.extractall(base)
        extracted = base / PACKAGE_NAME
        verify_internal_inventory(extracted)
        remove_replay_outputs(extracted)
        (extracted / "build").mkdir(parents=True, exist_ok=True)

        build = run_command([
            "cc", "-std=c99", "-O2", "-Wall", "-Wextra", "-Wpedantic",
            "-Isrc/c", "src/c/tomagi.c", "src/c/tomagi_cli.c", "-o", "build/tomagi-c",
        ], extracted)
        fixture = run_command([sys.executable, "tools/build_world04r_fixture.py"], extracted)
        artifact = run_command([sys.executable, "tools/build_world04r_release_artifact.py"], extracted)
        tests = run_command([
            sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"
        ], extracted)

        comparisons: dict[str, Any] = {}
        all_equal = True
        for rel, expected in expected_files.items():
            path = extracted / rel
            actual = sha256(path) if path.is_file() else None
            equal = actual == expected
            all_equal &= equal
            comparisons[rel] = {
                "packaged_sha256": expected,
                "replayed_sha256": actual,
                "equal": equal,
            }
        actual_store = tree_manifest(extracted / "examples/world04r/continuation_store")
        store_equal = actual_store == expected_store
        all_equal &= store_equal
        comparisons["examples/world04r/continuation_store/**"] = {
            "packaged": expected_store,
            "replayed": actual_store,
            "equal": store_equal,
        }
        if not all_equal:
            failed = [name for name, item in comparisons.items() if not item["equal"]]
            raise RuntimeError(f"clean final-archive replay mismatch: {failed}")

        import re
        tests_text = tests.stdout + tests.stderr
        match = re.search(r"Ran (\d+) tests", tests_text)
        test_count = int(match.group(1)) if match else 0
        if tests.returncode != 0 or test_count < 144 or not tests_text.rstrip().endswith("OK"):
            raise RuntimeError("full test suite from final archive did not pass")
        packaged_validation = json.loads((extracted / "validation/world04r/validation_report.json").read_text())
        if packaged_validation.get("status") != "pass" or packaged_validation.get("failure_count") != 0:
            raise RuntimeError("packaged corrective validation report is not passing")
        return {
            "zip_crc_and_safe_paths": True,
            "internal_manifest_and_checksums": True,
            "c_build": "pass",
            "fixture_rebuild": "pass",
            "release_artifact_rebuild": "pass",
            "full_test_suite": "pass",
            "full_tests": test_count,
            "packaged_validation_checks": packaged_validation["check_count"],
            "packaged_validation_failures": packaged_validation["failure_count"],
            "compared_file_boundaries": len(expected_files),
            "compared_tree_boundaries": 1,
            "all_replayed_boundaries_equal": True,
            "boundaries": comparisons,
            "command_output_hashes": {
                "c_build": sha256_bytes((build.stdout + build.stderr).encode("utf-8")),
                "fixture": sha256_bytes((fixture.stdout + fixture.stderr).encode("utf-8")),
                "release_artifact": sha256_bytes((artifact.stdout + artifact.stderr).encode("utf-8")),
                "tests": sha256_bytes(tests_text.encode("utf-8")),
            },
        }


def publish_companions() -> list[dict[str, Any]]:
    for name in COMPANIONS:
        (OUT / name).unlink(missing_ok=True)
    published: list[dict[str, Any]] = []
    for name, rel in sorted(COMPANIONS.items()):
        source = ROOT / rel
        destination = OUT / name
        destination.write_bytes(source.read_bytes())
        published.append({
            "path": destination.name,
            "source_in_package": rel,
            "bytes": destination.stat().st_size,
            "sha256": sha256(destination),
        })
    return published


